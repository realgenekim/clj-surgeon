(defn- parse-args
  [args]
  (loop [a args acc {:root (or (System/getenv "MEMBAT_ROOT") "/home/forge/tmp/membat")
                     :scales [100 1000 10000]}]
    (if-let [x (first a)]
      (case x
        "--root" (recur (drop 2 a) (assoc acc :root (second a)))
        "--scales" (recur (drop 2 a)
                          (assoc acc :scales
                                 (mapv #(Long/parseLong %)
                                       (str/split (second a) #","))))
        "--self-test" (recur (rest a) (assoc acc :self-test true))
        (recur (rest a) acc))
      acc)))

(defn- rm-rf! [f]
  (let [f (io/file f)]
    (when (.exists f)
      (when (.isDirectory f)
        (doseq [c (.listFiles f)] (rm-rf! c)))
      (.delete f))))

;; The no-op path is the one that can lie: it decides, without looking at the
;; corpus, that a table may print N=10,000. These assertions drive it against a
;; real three-file tree on disk.
(defn- verification-self-test! []
  (let [root (str (io/file (System/getProperty "java.io.tmpdir")
                           (str "membat-selftest-" (System/currentTimeMillis))))
        dir (io/file root "3")
        victim (io/file dir (rel-path-for 1))]
    (try
      (let [fresh (generate-tree! root 3)]
        (assert (false? (:reused fresh)) "first build generates")
        (assert (= 3 (:files fresh)) "three files written")
        (assert (= :ok (:status (verify-tree root 3)))
                "a tree that was just written verifies")
        (assert (true? (:reused (generate-tree! root 3)))
                "an intact tree is a no-op"))

      ;; A DELETED file must never be reported as present.
      (.delete victim)
      (assert (= :regenerate (:status (verify-tree root 3)))
              "a missing corpus file is detected, not trusted")
      (assert (= :missing-file (:reason (verify-tree root 3))))
      (assert (false? (:reused (generate-tree! root 3)))
              "a missing corpus file regenerates the tree")
      (assert (.exists victim) "regeneration restores the deleted file")

      ;; MODIFIED content must never pass on its byte count alone.
      (spit victim (str/replace (slurp victim) "defn-" "defn+"))
      (assert (= :content-mismatch (:reason (verify-tree root 3)))
              "same size, different bytes is caught by the content digest")
      (generate-tree! root 3)
      (assert (= :ok (:status (verify-tree root 3))))

      ;; EXTRA files are refused, not regenerated: regeneration would not remove
      ;; them, so it would loop, and deleting files under MEMBAT_ROOT is worse.
      (spit (io/file dir "src/membat/pkg000/intruder.clj") "(ns membat.intruder)")
      (assert (= :refuse (:status (verify-tree root 3)))
              "an unlisted file in the corpus is a refusal")
      (assert (= :unexpected-files (:reason (verify-tree root 3))))
      (.delete (io/file dir "src/membat/pkg000/intruder.clj"))

      ;; A SYMLINK at an expected path, even pointing at bytes identical to
      ;; the promised content, must never be reported as present: `.isFile`
      ;; follows symlinks, so a symlink to an out-of-tree copy of the same
      ;; file used to verify clean.
      (let [victim2 (io/file dir (rel-path-for 2))
            outside (io/file root "outside-target.clj")]
        (spit outside (slurp victim2))
        (.delete victim2)
        (Files/createSymbolicLink (.toPath victim2) (.toPath outside)
                                  (make-array java.nio.file.attribute.FileAttribute 0))
        (assert (= :refuse (:status (verify-tree root 3)))
                "a symlink at an expected path is refused, not verified")
        (assert (= :symlink-at-expected-path (:reason (verify-tree root 3))))
        (Files/delete (.toPath victim2))
        (generate-tree! root 3)
        (assert (= :ok (:status (verify-tree root 3)))
                "regeneration restores a plain file after the symlink is removed"))

      ;; A DIRECTORY at an expected path must be a typed refusal raised BEFORE
      ;; any write, not an untyped FileNotFoundException thrown mid-spit.
      (let [victim3 (io/file dir (rel-path-for 0))]
        (.delete victim3)
        (.mkdirs victim3)
        (assert (= :refuse (:status (verify-tree root 3)))
                "a directory at an expected path is refused, not silently missing")
        (assert (= :directory-at-expected-path (:reason (verify-tree root 3))))
        ;; generate-tree! must refuse the same way, typed, and must not throw
        ;; the JVM's own untyped "Is a directory" I/O exception.
        (let [threw (try (generate-tree! root 3) :did-not-throw
                         (catch clojure.lang.ExceptionInfo e
                           (:reason (ex-data e)))
                         (catch Exception e
                           [:untyped (class e)]))]
          (assert (= :directory-at-expected-path threw)
                  (str "generate-tree! refuses typed, not: " (pr-str threw))))
        (.delete victim3)
        (generate-tree! root 3)
        (assert (= :ok (:status (verify-tree root 3)))
                "regeneration restores a plain file after the directory is removed"))

      ;; A TAMPERED manifest digest is not authority over the bytes.
      (let [mf (io/file dir "manifest.edn")]
        (spit mf (pr-str (assoc (read-string (slurp mf)) :digest "deadbeef")))
        (assert (= :digest-mismatch (:reason (verify-tree root 3)))
                "the manifest digest is rechecked against the actual bytes"))
      ;; Every adversarial arm builds, verifies, and reuses — and is the shape
      ;; it claims to be. These are separate corpora, so each gets its own
      ;; directory and its own manifest.
      (doseq [[profile n] profile-arms]
        (let [m (generate-tree! root profile n)]
          (assert (false? (:reused m)) (str profile " builds"))
          (assert (= n (:files m)) (str profile " file count"))
          (assert (= profile (:profile m)) (str profile " is recorded"))
          (assert (= :ok (:status (verify-tree root profile n)))
                  (str profile " verifies"))
          (assert (true? (:reused (generate-tree! root profile n)))
                  (str profile " reuses"))
          (assert (.isDirectory (io/file root (tree-dir-name profile n)))
                  (str profile " has its own corpus directory"))))

      (let [cljc (slurp (io/file root (tree-dir-name :cljc 100)
                                  (rel-path-for-profile :cljc 3)))
            giant (io/file root (tree-dir-name :giant 1)
                           (rel-path-for-profile :giant 0))
            nested (slurp (io/file root (tree-dir-name :nested 1)
                                   (rel-path-for-profile :nested 0)))]
        (assert (str/includes? cljc "#?(:clj") "cljc carries reader conditionals")
        (assert (str/includes? cljc "#?@(:clj") "cljc carries splicing conditionals")
        (assert (str/ends-with? (.getName giant) ".clj"))
        (assert (>= (.length giant) 1900000)
                (str "the giant arm is ~1.9 MiB, got " (.length giant)))
        (assert (= nesting-depth (count (re-seq #"\{:k \[" nested)))
                "the nested arm reaches its stated depth")
        (assert (str/includes? nested "(def dense") "the nested arm is token-dense")
        (assert (< (count nested) 200000)
                "the nested arm stresses node count, not byte count"))

      (println "generate_tree verification self-test: ok")
      (finally (rm-rf! root)))))

;; MEMBAT_ROOT is arbitrary and, before this, had no marker or scope guard: a
;; fresh root auto-created whatever it pointed at, and a shared/pre-existing
;; directory (potentially unrelated to the battery) was written into on the
;; same footing as a battery-owned one.
(defn- root-marker-self-test! []
  (let [base "/home/forge/tmp"
        stamp (System/currentTimeMillis)
        fresh-root (io/file base (str "membat-marker-selftest-" stamp))
        unmarked-root (io/file base (str "membat-unmarked-selftest-" stamp))
        outside-root (io/file (System/getProperty "java.io.tmpdir")
                              (str "membat-outside-selftest-" stamp))]
    (try
      ;; A fresh root is created and marked by the battery itself.
      (ensure-root-marker! (str fresh-root))
      (assert (.isDirectory fresh-root) "a fresh root is created")
      (assert (.exists (io/file fresh-root ".membat-root"))
              "a fresh root is marked")
      ;; Reusing an already-marked root is a no-op, not a refusal.
      (ensure-root-marker! (str fresh-root))

      ;; A pre-existing root with NO marker is refused, not silently adopted
      ;; — it might be $HOME, a real repo, or another tool's directory.
      (.mkdirs unmarked-root)
      (let [reason (try (ensure-root-marker! (str unmarked-root)) :did-not-throw
                        (catch clojure.lang.ExceptionInfo e (:reason (ex-data e))))]
        (assert (= :membat-root-unmarked reason)
                (str "an unmarked pre-existing root is refused, got " reason)))

      ;; A root outside /home/forge/tmp is refused by default...
      (let [reason (try (ensure-root-marker! (str outside-root) false) :did-not-throw
                        (catch clojure.lang.ExceptionInfo e (:reason (ex-data e))))]
        (assert (= :membat-root-outside-allowed reason)
                (str "a root outside the allowed scope is refused, got " reason)))
      (assert (not (.exists outside-root))
              "a refused outside-scope root is never created")

      ;; ...unless the caller explicitly opts in (MEMBAT_ALLOW_ANY_ROOT=1).
      (ensure-root-marker! (str outside-root) true)
      (assert (.isDirectory outside-root)
              "an explicit override creates and marks an outside-scope root")

      (println "generate_tree root-marker self-test: ok")
      (finally
        (rm-rf! fresh-root)
        (rm-rf! unmarked-root)
        (rm-rf! outside-root)))))

(defn- self-test! []
  (let [a (file-source 3 100)
        b (file-source 3 100)
        c (file-source 9 100)]
    (assert (= a b) "generator must be deterministic")
    (assert (not= a c) "different indices must produce different sources")
    (assert (str/includes? a "(ns membat.pkg000.mod00003") "ns form")
    (assert (str/includes? a "(defmethod render-00003 :alpha") "multimethod arm")
    (assert (>= (count c) (:large size-buckets)) "large bucket reaches its target")
    (assert (< (count a) (:medium size-buckets)) "small bucket stays small")
    (assert (= :small (bucket-for 0)))
    (assert (= :medium (bucket-for 6)))
    (assert (= :large (bucket-for 9)))
    (verification-self-test!)
    (root-marker-self-test!)
    (println "generate_tree self-test: ok")
    0))

(defn -main [& args]
  (let [{:keys [root scales self-test]} (parse-args args)]
    (if self-test
      (System/exit (self-test!))
      (do
        (try
          (ensure-root-marker! root)
          (catch clojure.lang.ExceptionInfo e
            (binding [*out* *err*]
              (println "REFUSED:" (.getMessage e))
              (println (pr-str (ex-data e))))
            (System/exit 2)))
        (doseq [[profile n] (into (vec (for [n (sort scales)] [:default n]))
                                  profile-arms)]
          (let [t0 (System/currentTimeMillis)
                m (try
                    (generate-tree! root profile n)
                    (catch clojure.lang.ExceptionInfo e
                      (binding [*out* *err*]
                        (println "REFUSED:" (.getMessage e))
                        (println (pr-str (ex-data e))))
                      (System/exit 2)))
                ms (- (System/currentTimeMillis) t0)]
            (println (format "%-10s files=%-7d bytes=%-11d mean=%-8d largest=%-8d %s (%d ms)"
                             (tree-dir-name profile n)
                             (:files m) (:bytes m) (:mean-file-bytes m)
                             (:largest-file-bytes m)
                             (if (:reused m)
                               "verified"
                               (str "generated:" (name (or (:verified-reason m)
                                                           :no-manifest))))
                             ms))))
        (System/exit 0)))))

(when (= *file* (System/getProperty "babashka.file"))
  (apply -main *command-line-args*))
