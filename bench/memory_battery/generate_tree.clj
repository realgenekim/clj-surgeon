(defn- parse-args
  [args]
  (loop [a args acc {:root (or (System/getenv "MEMBAT_ROOT") "/home/forge/tmp/membat")
                     :scales [100 1000 10000]}]
    (if-let [x (first a)]
      (case x
        "--root" (recur (drop 2 a) (assoc acc :root (second a)))
        "--scales" (recur (drop 2 a)
                          (assoc acc :scales
                                 (mapv #(Long/parseLong %)
                                       (str/split (second a) #","))))
        "--self-test" (recur (rest a) (assoc acc :self-test true))
        (recur (rest a) acc))
      acc)))

(defn- self-test! []
  (let [a (file-source 3 100)
        b (file-source 3 100)
        c (file-source 9 100)]
    (assert (= a b) "generator must be deterministic")
    (assert (not= a c) "different indices must produce different sources")
    (assert (str/includes? a "(ns membat.pkg000.mod00003") "ns form")
    (assert (str/includes? a "(defmethod render-00003 :alpha") "multimethod arm")
    (assert (>= (count c) (:large size-buckets)) "large bucket reaches its target")
    (assert (< (count a) (:medium size-buckets)) "small bucket stays small")
    (assert (= :small (bucket-for 0)))
    (assert (= :medium (bucket-for 6)))
    (assert (= :large (bucket-for 9)))
    (println "generate_tree self-test: ok")
    0))

(defn -main [& args]
  (let [{:keys [root scales self-test]} (parse-args args)]
    (if self-test
      (System/exit (self-test!))
      (do
        (doseq [n scales]
          (let [t0 (System/currentTimeMillis)
                m (generate-tree! root n)
                ms (- (System/currentTimeMillis) t0)]
            (println (format "%-8s files=%-7d bytes=%-11d mean=%-6d largest=%-7d %s (%d ms)"
                             (str n) (:files m) (:bytes m) (:mean-file-bytes m)
                             (:largest-file-bytes m)
                             (if (:reused m) "reused" "generated") ms))))
        (System/exit 0)))))

(when (= *file* (System/getProperty "babashka.file"))
  (apply -main *command-line-args*))
