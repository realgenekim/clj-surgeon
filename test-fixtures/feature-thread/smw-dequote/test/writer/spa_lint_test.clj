  (let [app (slurp "resources/public/js/editor-controller.js")
        runtime (slurp "resources/public/js/datastar-runtime.js")
        save-form (second (re-find #"(?s)(async function saveDraft.*?\n\})" app))
        open-form (second (re-find #"(?s)(async function openBookNode.*?\n\})" runtime))]
    (testing "Save sends one request carrying the visible snapshot"
      (is (str/includes? save-form "const sync = collectDraftSync()"))
      (is (str/includes? save-form "await postJSON('/api/save'"))
      (is (not (str/includes? save-form "flushDraftSync()"))
          "never restore the parallel flush + save race")
      (is (str/includes? save-form "setHeaderSaveStatus('Saving…', 'saving')"))
      (is (str/includes? save-form "setHeaderSaveStatus('Conflict', 'conflict')"))
      (is (str/includes? save-form "setHeaderSaveStatus('Failed', 'failed')"))
      ;; INTENT-TEST: EDITOR-QUAR-001 — the clearing authority is explicit and
      ;; belongs only to the force-conflict path.
      ;; INTENT-TEST: EDITOR-DURA-007 — and only when that path was durably
      ;; confirmed: un-saved implies un-resolved.
      (is (str/includes? save-form
                         "applyEditorAck(response, {resolvesConflict: !!forceConflict && durableOk})"))
      (is (< (str/index-of save-form "const durableOk =")
             (str/index-of save-form "applyEditorAck(response,"))
          "durability is decided before the acknowledgement is granted clearing authority")
      (is (< (str/index-of save-form "applyEditorAck(response,")
             (str/index-of save-form "setHeaderSaveStatus('Saved', 'saved')"))
          "Saved is only painted after the exact response acknowledgement passes"))
    (testing "node open applies one complete authoritative response frame"
      (is (str/includes? open-form "beginEditorCommand('open node')"))
      (is (str/includes? open-form "await postJSON('/api/book/open-node'"))
      (is (str/includes? open-form
                         "applyAuthoritativeEditorFrame(frame, 'identity-change', draftSync)")
          "node open must fence the returned frame with the gesture-time snapshot")
      (is (not (str/includes? open-form "await waitForEditorFrame"))
          "never release single-flight after an SSE delivery timeout"))))







































































































































































































































































(deftest transform-button-and-shortcut-share-one-browser-selection-path
  (let [commands (slurp "resources/public/js/editor-commands.js")
        view (slurp "src/writer/views/draft_chat.clj")
        components (slurp "src/writer/views/components.clj")]
    (is (str/includes? commands "function openTransformFromSelection()"))
    (is (str/includes? commands "postJSON('/api/transform/open', {selected})"))
    (is (str/includes? commands "event.code === 'KeyT'"))
    (is (str/includes? commands "openTransformFromSelection();"))
    (is (str/includes? view ":onmousedown \"event.preventDefault()\""))
    (is (str/includes? view
                       ":onclick \"hideSelectionToolbar();openTransformFromSelection()\""))
    (is (str/includes? components ":onclick \"openTransformFromSelection()\""))
    (is (str/includes? view "[:span \"Transform\"]"))))







































































