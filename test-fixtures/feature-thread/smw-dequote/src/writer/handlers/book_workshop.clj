  "Compound Save Back command. The visible snapshot is identity/version
   validated, mirrored into the stable-ID node, durably settled, and only then
   is editing mode cleared. No separate flush request may race this handler."
  [request]
  (let [{:keys [sync]} (try (http/parse-json-body request) (catch Exception _ {}))]
    (if-not (map? sync)
      {:status 400 :body "Visible editor snapshot required"}
      (try
        (if-let [{:keys [project-id node-id] :as editing-node}
                 (state/editing-node-location @state/app-state)]
          (let [journal-headers (editor-journal/journal-receipt sync)
                transition-params {:project-id project-id :node-id node-id}
                res (dispatch/fold-editor-snapshot-and-transition!
                      :book-save-from-draft
                      transition-params
                      sync
                      (fn [current]
                        (if (= node-id
                               (get-in current
                                       [:book-workshop :editing-node :node-id]))
                          (-> current
                              (assoc-in [:book-workshop :editing-node] nil)
                              (assoc-in [:ui :active-top-tab] :book-workshop))
                          current)))]
            (if-not (dispatch/book-ack-ok? (:book res))
              (book-durability-response {:book (:book res)
                                         :state-version (:revision res)})
              (let [draft (:draft sync)
                    context (:context sync)
                    _ (try
                        (save-book-draft-snapshot! editing-node draft context)
                        (catch Exception e
                          (log/warn e :book/save-back-snapshot-failed
                                    :node-id node-id)))
                    session-ack (state/save-session!)
                    response (book-editor-frame-response
                               {:book (:book res)
                                :state-version (:revision res)})
                    response (cond-> response
                               journal-headers
                               (update :headers merge journal-headers)

                               true
                               (assoc-in [:headers "X-Session-Durable"]
                                         (str (boolean (or (nil? session-ack)
                                                           (:ok session-ack))))))]
                (sse/push-book-trees!)
                (sse/push-top-tabs!)
                (sse/push-switch-tab! "book-workshop")
                (sse/push-body-data!)
                (sse/push-editor-pane!)
                (sse/clear-draft-sync-conflict!)
                (sse/push-notify! "Saved to book node")
                response)))
          (do
            (sse/push-notify! "⚠ Save failed: active Book node identity is missing")
            {:status 409}))
        (catch clojure.lang.ExceptionInfo e
          (let [conflict (ex-data e)]
            (if (#{"stale-version" "stale-editor" "conflict-changed" "invalid-editor-state"
                   "unsettled-editor-projection"} (:reason conflict))
              (editor-conflict-response "book.save-from-draft" conflict)
              (throw e))))))))























































































































































































